-- محادثات الدعم الفني بين الزوار وفريق أوكسين.
--
-- الزائر بيفتح محادثة من صفحة /chat ويستقبل token عشوائي غير قابل للتخمين،
-- وده اللي بيستخدمه في قراءة رسايله وكتابة رسايل جديدة. الجداول نفسها
-- مقفولة تمامًا (RLS من غير policies)، والوصول بيتم فقط عبر الدوال تحت.
-- الأدمن بيستخدم دوال منفصلة بتتحقق من دوره في الـ JWT.
--
-- idempotent: ينفع يتنفذ أكثر من مرة.

create table if not exists public.support_conversations (
  id uuid primary key default gen_random_uuid(),
  token uuid not null unique default gen_random_uuid(),
  visitor_name text not null default '',
  visitor_email text not null default '',
  status text not null default 'open' check (status in ('open', 'closed')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  last_message_at timestamptz
);

create table if not exists public.support_messages (
  id bigint generated by default as identity primary key,
  conversation_id uuid not null references public.support_conversations(id) on delete cascade,
  sender text not null check (sender in ('visitor', 'agent')),
  body text not null check (char_length(body) between 1 and 4000),
  read_by_recipient boolean not null default false,
  created_at timestamptz not null default now()
);

create index if not exists idx_support_messages_conversation
  on public.support_messages (conversation_id, created_at);
create index if not exists idx_support_messages_unread_visitor
  on public.support_messages (created_at)
  where sender = 'visitor' and not read_by_recipient;
create index if not exists idx_support_conversations_last
  on public.support_conversations (last_message_at desc nulls last);

alter table public.support_conversations enable row level security;
alter table public.support_messages enable row level security;

revoke all on public.support_conversations from public, anon, authenticated;
revoke all on public.support_messages from public, anon, authenticated;
grant select, insert, update, delete on public.support_conversations to service_role;
grant select, insert, update, delete on public.support_messages to service_role;
grant usage, select on sequence public.support_messages_id_seq to service_role;

-- ---------------------------------------------------------------------------
-- هل المتصل عضو فريق دعم؟ (owner / admin / support)
-- ---------------------------------------------------------------------------
create or replace function public.awexen_support_is_agent()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select coalesce((select auth.jwt()) -> 'app_metadata' ->> 'role', '')
    in ('owner', 'admin', 'support');
$$;

-- ---------------------------------------------------------------------------
-- الزائر: بدء محادثة جديدة.
-- ---------------------------------------------------------------------------
create or replace function public.awexen_support_start(
  p_name text default '',
  p_email text default ''
)
returns table (token uuid, conversation_id uuid)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_token uuid;
  v_id uuid;
begin
  insert into public.support_conversations (visitor_name, visitor_email)
  values (
    left(btrim(coalesce(p_name, '')), 120),
    left(btrim(coalesce(p_email, '')), 200)
  )
  returning support_conversations.token, support_conversations.id into v_token, v_id;

  return query select v_token, v_id;
end;
$$;

-- ---------------------------------------------------------------------------
-- الزائر: إرسال رسالة. Token غلط أو محادثة مقفولة = خطأ.
-- ---------------------------------------------------------------------------
create or replace function public.awexen_support_send(
  p_token uuid,
  p_body text
)
returns table (id bigint, sender text, body text, created_at timestamptz)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_body text := btrim(coalesce(p_body, ''));
  v_id uuid;
begin
  if v_body = '' then
    raise exception 'اكتب رسالتك أولًا.' using errcode = '22023';
  end if;
  if char_length(v_body) > 2000 then
    raise exception 'الرسالة طويلة جدًا. الحد 2000 حرف.' using errcode = '22023';
  end if;

  select c.id into v_id
  from public.support_conversations c
  where c.token = p_token;

  if v_id is null then
    raise exception 'المحادثة غير متاحة.' using errcode = 'P0002';
  end if;

  if (
    select count(*)
    from public.support_messages m
    where m.conversation_id = v_id
      and m.sender = 'visitor'
      and m.created_at > now() - interval '1 minute'
  ) >= 20 then
    raise exception 'تم إرسال رسائل كثيرة. استنى دقيقة وجرب تاني.' using errcode = 'P0001';
  end if;

  return query
  with inserted as (
    insert into public.support_messages as m (conversation_id, sender, body)
    values (v_id, 'visitor', v_body)
    returning m.id, m.sender, m.body, m.created_at
  )
  select inserted.id, inserted.sender, inserted.body, inserted.created_at from inserted;

  update public.support_conversations
  set status = 'open', last_message_at = now(), updated_at = now()
  where id = v_id;
end;
$$;

-- ---------------------------------------------------------------------------
-- الزائر: تحديث بياناته (اختاري) عشان الفريق يعرف مين بيكلمه.
-- ---------------------------------------------------------------------------
create or replace function public.awexen_support_identify(
  p_token uuid,
  p_name text default '',
  p_email text default ''
)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  update public.support_conversations
  set visitor_name = case
        when btrim(coalesce(p_name, '')) <> '' then left(btrim(p_name), 120)
        else visitor_name
      end,
      visitor_email = case
        when btrim(coalesce(p_email, '')) <> '' then left(btrim(p_email), 200)
        else visitor_email
      end,
      updated_at = now()
  where token = p_token;
end;
$$;

-- ---------------------------------------------------------------------------
-- الزائر: قراءة الرسائل (وبنعتبر رسايل الفريق اتقرأت).
-- ---------------------------------------------------------------------------
create or replace function public.awexen_support_fetch(p_token uuid)
returns table (id bigint, sender text, body text, created_at timestamptz)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_id uuid;
begin
  select c.id into v_id
  from public.support_conversations c
  where c.token = p_token;

  if v_id is null then
    return;
  end if;

  update public.support_messages
  set read_by_recipient = true
  where conversation_id = v_id
    and sender = 'agent'
    and not read_by_recipient;

  return query
  select m.id, m.sender, m.body, m.created_at
  from public.support_messages m
  where m.conversation_id = v_id
  order by m.created_at asc, m.id asc;
end;
$$;

-- ---------------------------------------------------------------------------
-- الأدمن: قائمة المحادثات مع آخر رسالة وعدد غير المقروء.
-- ---------------------------------------------------------------------------
create or replace function public.awexen_support_admin_list()
returns table (
  id uuid,
  visitor_name text,
  visitor_email text,
  status text,
  created_at timestamptz,
  last_message_at timestamptz,
  last_message text,
  unread_count bigint,
  message_count bigint
)
language plpgsql
stable
security definer
set search_path = public
as $$
begin
  if not public.awexen_support_is_agent() then
    raise exception 'غير مصرّح بالوصول لمحادثات الدعم.' using errcode = '42501';
  end if;

  return query
  select
    c.id,
    c.visitor_name,
    c.visitor_email,
    c.status,
    c.created_at,
    c.last_message_at,
    (
      select m.body
      from public.support_messages m
      where m.conversation_id = c.id
      order by m.created_at desc, m.id desc
      limit 1
    ),
    (
      select count(*)
      from public.support_messages m
      where m.conversation_id = c.id
        and m.sender = 'visitor'
        and not m.read_by_recipient
    ),
    (
      select count(*)
      from public.support_messages m
      where m.conversation_id = c.id
    )
  from public.support_conversations c
  order by coalesce(c.last_message_at, c.created_at) desc
  limit 200;
end;
$$;

-- ---------------------------------------------------------------------------
-- الأدمن: رسائل محادثة واحدة + تعليم رسايل الزائر كمقروءة.
-- ---------------------------------------------------------------------------
create or replace function public.awexen_support_admin_thread(p_conversation_id uuid)
returns table (id bigint, sender text, body text, created_at timestamptz)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_found boolean;
begin
  if not public.awexen_support_is_agent() then
    raise exception 'غير مصرّح بالوصول لمحادثات الدعم.' using errcode = '42501';
  end if;

  select true into v_found
  from public.support_conversations c
  where c.id = p_conversation_id;

  if v_found is null then
    raise exception 'المحادثة غير موجودة.' using errcode = 'P0002';
  end if;

  update public.support_messages
  set read_by_recipient = true
  where conversation_id = p_conversation_id
    and sender = 'visitor'
    and not read_by_recipient;

  return query
  select m.id, m.sender, m.body, m.created_at
  from public.support_messages m
  where m.conversation_id = p_conversation_id
  order by m.created_at asc, m.id asc;
end;
$$;

-- ---------------------------------------------------------------------------
-- الأدمن: رد على الزائر.
-- ---------------------------------------------------------------------------
create or replace function public.awexen_support_admin_reply(
  p_conversation_id uuid,
  p_body text
)
returns table (id bigint, sender text, body text, created_at timestamptz)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_body text := btrim(coalesce(p_body, ''));
  v_status text;
begin
  if not public.awexen_support_is_agent() then
    raise exception 'غير مصرّح بالرد على المحادثات.' using errcode = '42501';
  end if;

  if v_body = '' then
    raise exception 'اكتب الرد أولًا.' using errcode = '22023';
  end if;
  if char_length(v_body) > 4000 then
    raise exception 'الرد طويل جدًا. الحد 4000 حرف.' using errcode = '22023';
  end if;

  select c.status into v_status
  from public.support_conversations c
  where c.id = p_conversation_id;

  if v_status is null then
    raise exception 'المحادثة غير موجودة.' using errcode = 'P0002';
  end if;
  if v_status <> 'open' then
    raise exception 'المحادثة مغلقة. افتحها الأول قبل الرد.' using errcode = 'P0001';
  end if;

  return query
  with inserted as (
    insert into public.support_messages as m (conversation_id, sender, body)
    values (p_conversation_id, 'agent', v_body)
    returning m.id, m.sender, m.body, m.created_at
  )
  select inserted.id, inserted.sender, inserted.body, inserted.created_at from inserted;

  update public.support_conversations
  set last_message_at = now(), updated_at = now()
  where id = p_conversation_id;
end;
$$;

-- ---------------------------------------------------------------------------
-- الأدمن: فتح/قفل المحادثة.
-- ---------------------------------------------------------------------------
create or replace function public.awexen_support_admin_set_status(
  p_conversation_id uuid,
  p_status text
)
returns table (conversation_status text)
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.awexen_support_is_agent() then
    raise exception 'غير مصرّح بتعديل المحادثات.' using errcode = '42501';
  end if;

  if p_status is null or p_status not in ('open', 'closed') then
    raise exception 'حالة المحادثة غير صحيحة.' using errcode = '22023';
  end if;

  update public.support_conversations
  set status = p_status, updated_at = now()
  where id = p_conversation_id;

  if not found then
    raise exception 'المحادثة غير موجودة.' using errcode = 'P0002';
  end if;

  return query
  select c.status
  from public.support_conversations c
  where c.id = p_conversation_id;
end;
$$;

-- ---------------------------------------------------------------------------
-- الأدمن: عدد رسايل الزوار غير المقروءة (للإشعارات في لوحة التحكم).
-- ---------------------------------------------------------------------------
create or replace function public.awexen_support_admin_unread()
returns bigint
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_count bigint;
begin
  if not public.awexen_support_is_agent() then
    return 0;
  end if;

  select count(*) into v_count
  from public.support_messages m
  where m.sender = 'visitor'
    and not m.read_by_recipient;

  return v_count;
end;
$$;

