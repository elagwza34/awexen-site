-- طلبات مبادرة تصميم موقع إلكتروني مجانًا لبيزنس واحد.
-- نفس نموذج الوصول بتاع quote_requests: الزائر يُدرج فقط، والإدارة
-- تقرأ وتعدّل وتحذف من خلال لوحة التحكم.
-- idempotent: ينفع يتنفذ على قاعدة فيها الجدول من قبل.

create table if not exists public.initiative_applications (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null,
  phone text,
  business_type text not null,
  target_audience text not null,
  biggest_challenge text not null,
  how_website_helps text not null,
  status text not null default 'new',
  admin_notes text,
  created_at timestamptz not null default now()
);

create index if not exists idx_initiative_applications_created_at
  on public.initiative_applications (created_at desc);

create index if not exists idx_initiative_applications_email
  on public.initiative_applications (email);

alter table public.initiative_applications enable row level security;

-- الزائر يُدرج فقط، مع تحقق أساسي من القيم.
drop policy if exists "Allow public insert to initiative_applications"
  on public.initiative_applications;

create policy "Allow public insert to initiative_applications"
on public.initiative_applications
for insert
to anon, authenticated
with check (
  char_length(trim(name)) between 2 and 100
  and char_length(trim(email)) between 5 and 254
  and position('@' in email) > 1
  and char_length(trim(business_type)) between 5 and 2000
  and char_length(trim(target_audience)) between 5 and 2000
  and char_length(trim(biggest_challenge)) between 5 and 2000
  and char_length(trim(how_website_helps)) between 5 and 2000
  and (phone is null or char_length(trim(phone)) <= 30)
);

-- البيانات ما تتف-readش من المتصفح أبدًا، بس للإدارة.
drop policy if exists "Allow public read of initiative_applications"
  on public.initiative_applications;

drop policy if exists "Allow admins to read initiative_applications"
  on public.initiative_applications;

create policy "Allow admins to read initiative_applications"
on public.initiative_applications
for select
to authenticated
using (public.lms_can_review_payments());

-- الإدارة تقدر تعدّل الحالة والملاحظات.
drop policy if exists "Allow admins to update initiative_applications"
  on public.initiative_applications;

create policy "Allow admins to update initiative_applications"
on public.initiative_applications
for update
to authenticated
using (public.lms_can_review_payments())
with check (public.lms_can_review_payments());

-- الإدارة تحذف الطلب بعد التعامل معه.
drop policy if exists "Allow admins to delete initiative_applications"
  on public.initiative_applications;

create policy "Allow admins to delete initiative_applications"
on public.initiative_applications
for delete
to authenticated
using (public.lms_can_review_payments());

-- الزائر يُدرج فقط؛ لا قراءة ولا تعديل ولا حذف.
revoke all on table public.initiative_applications from anon, authenticated;
grant insert on table public.initiative_applications to anon, authenticated;
grant select, update, delete on table public.initiative_applications to authenticated;
grant usage, select on sequence public.initiative_applications_id_seq
  to anon, authenticated;