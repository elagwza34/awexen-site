-- طلبات مبادرة تصميم موقع إلكتروني مجانًا لبيزنس واحد.
-- نفس نموذج الوصول بتاع quote_requests: الزائر يُدرج فقط، والإدارة
-- تقرأ وتعدّل وتحذف من خلال لوحة التحكم.
-- idempotent: ينفع يتنفذ على قاعدة فيها الجدول من قبل.

create table if not exists public.initiative_applications (
  id bigint generated by default as identity primary key,
  applicant_name text not null,
  whatsapp_number text not null,
  email text not null,
  city text not null,
  business_name text not null,
  business_sector text not null,
  custom_business_sector text,
  business_description text not null,
  business_age text not null,
  social_media_url text,
  target_audience text not null,
  biggest_challenge text not null,
  custom_challenge text,
  has_website text not null default 'no',
  website_url text,
  website_necessity text not null,
  website_objective text not null,
  custom_website_objective text,
  six_month_goal text not null,
  content_readiness text not null,
  cooperation_readiness text not null,
  terms_accepted boolean not null default false,
  terms_version text not null default '1.0',
  status text not null default 'new',
  admin_notes text,
  submitted_at timestamptz not null default now()
);

