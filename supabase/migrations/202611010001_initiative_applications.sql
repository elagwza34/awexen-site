-- السياسة: الزائر يُدرج فقط، بلا قراءة من المتصفح.
drop policy if exists "Allow public insert to initiative_applications"
  on public.initiative_applications;

create policy "Allow public insert to initiative_applications"
on public.initiative_applications
for insert
to anon, authenticated
with check (
  char_length(trim(applicant_name)) between 2 and 100
  and char_length(trim(whatsapp_number)) between 10 and 30
  and char_length(trim(email)) between 5 and 254
  and char_length(trim(email)) > 0
  and char_length(trim(business_name)) between 2 and 200
  and char_length(trim(business_description)) between 20 and 2000
  and char_length(trim(target_audience)) between 10 and 2000
  and char_length(trim(biggest_challenge)) between 3 and 2000
  and char_length(trim(six_month_goal)) between 10 and 2000
);

-- البيانات ما تتف-readش من المتصفح أبدًا، بس للإدارة.
drop policy if exists "Allow public read of initiative_applications"
  on public.initiative_applications;

drop policy if exists "Allow admins to read initiative_applications"
  on public.initiative_applications;

create policy "Allow admins to read initiative_applications"
on public.initiative_applications
for select
to authenticated
using (public.lms_can_review_payments());

-- الإدارة تقدر تعدّل الحالة والملاحظات.
drop policy if exists "Allow admins to update initiative_applications"
  on public.initiative_applications;

create policy "Allow admins to update initiative_applications"
on public.initiative_applications
for update
to authenticated
using (public.lms_can_review_payments())
with check (public.lms_can_review_payments());

-- الإدارة تحذف الطلب بعد التعامل معه.
