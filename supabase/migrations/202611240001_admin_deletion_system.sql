-- نظام حذف سجلات الموقع العامة من لوحة التحكم.
-- القاعدة: الحذف المباشر من المتصفح مقفول لهذه الجداول، والحذف بيتم فقط
-- عبر دالة واحدة تتحقق من الدور، تطبّق قواعد حماية السجلات، وتسجّل العملية.
--
-- idempotent: ينفع يتنفذ أكثر من مرة.

-- ---------------------------------------------------------------------------
-- 1) أرشفة عروض الأسعار التي لها قيمة مالية.
-- ---------------------------------------------------------------------------
alter table public.quote_requests
  add column if not exists deleted_at timestamptz;
alter table public.quote_requests
  add column if not exists deleted_by uuid;
alter table public.quote_requests
  add column if not exists deletion_reason text;

create index if not exists idx_quote_requests_active_created
  on public.quote_requests (created_at desc)
  where deleted_at is null;

-- ---------------------------------------------------------------------------
-- 2) سجل تدقيق الحذف — append-only.
-- بنحفظ المعرّفات والاسم/البريد المختصر فقط، مش محتوى الرسالة الكامل.
-- ---------------------------------------------------------------------------
create table if not exists public.admin_deletion_log (
  id bigint generated by default as identity primary key,
  actor_id uuid,
  actor_email text,
  actor_role text,
  target_table text not null,
  action text not null check (action in ('hard_delete', 'soft_delete')),
  record_ids jsonb not null default '[]'::jsonb,
  record_labels jsonb not null default '[]'::jsonb,
  record_count integer not null default 0,
  reason text,
  created_at timestamptz not null default now()
);

create index if not exists idx_admin_deletion_log_created_at
  on public.admin_deletion_log (created_at desc);
create index if not exists idx_admin_deletion_log_table
  on public.admin_deletion_log (target_table, created_at desc);

alter table public.admin_deletion_log enable row level security;

revoke all on table public.admin_deletion_log from anon, authenticated;
grant select on table public.admin_deletion_log to authenticated;

create schema if not exists private;

create or replace function private.awexen_reject_audit_change()
returns trigger
language plpgsql
set search_path = pg_catalog
as $$
begin
  raise exception using
    errcode = '55000',
    message = 'public.admin_deletion_log is append-only.';
end;
$$;

drop trigger if exists admin_deletion_log_append_only on public.admin_deletion_log;
create trigger admin_deletion_log_append_only
before update or delete on public.admin_deletion_log
for each row execute function private.awexen_reject_audit_change();

-- ---------------------------------------------------------------------------
-- 3) صلاحية الحذف: مالك/مدير Awexen، أو super_admin / organization_admin في LMS.
-- ---------------------------------------------------------------------------
create or replace function public.awexen_can_delete_records()
returns boolean
language sql
stable
security definer
set search_path = pg_catalog, public
as $$
  select public.is_awexen_owner_or_admin()
    or exists (
      select 1 from public.accounts_user u
      where u.id = public.lms_user_id()
        and u.is_active
        and u.platform_role = 'super_admin'
    )
    or exists (
      select 1 from public.organizations_membership m
      where m.user_id = public.lms_user_id()
        and m.is_active
        and m.role = 'organization_admin'
    );
$$;

revoke all on function public.awexen_can_delete_records() from public, anon;
grant execute on function public.awexen_can_delete_records()
  to authenticated, service_role;

drop policy if exists "Allow admins to read admin_deletion_log"
  on public.admin_deletion_log;

create policy "Allow admins to read admin_deletion_log"
on public.admin_deletion_log
for select
to authenticated
using (public.awexen_can_delete_records());

-- ---------------------------------------------------------------------------
-- 4) دالة الحذف الموحّدة.
--   - contact_messages / initiative_applications / newsletter_subscribers /
--     ai_inquiries: حذف نهائي (سجلات واردة قابلة للتخلص منها).
--   - quote_requests: حذف نهائي للطلبات الجديدة، وأرشفة (soft delete) لأي طلب
--     له عرض سعر أو مقبول، حفاظًا على السجل التجاري.
--   - job_applications: حذف نهائي، مع منع حذف المتقدمين المقبولين.
-- ---------------------------------------------------------------------------
create or replace function public.awexen_admin_delete_records(
  p_table text,
  p_ids text[],
  p_reason text default null
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  v_actor uuid := auth.uid();
  v_email text := coalesce(auth.jwt() ->> 'email', '');
  v_role text := coalesce(auth.jwt() -> 'app_metadata' ->> 'role', '');
  v_reason text := nullif(left(btrim(coalesce(p_reason, '')), 500), '');
  v_text_ids text[];
  v_bigint_ids bigint[];
  v_uuid_ids uuid[];
  v_deleted_ids text[] := '{}'::text[];
  v_archived_ids text[] := '{}'::text[];
  v_blocked jsonb := '[]'::jsonb;
  v_labels jsonb := '[]'::jsonb;
  v_storage jsonb := '[]'::jsonb;
begin
  if v_actor is null then
    raise exception 'يجب تسجيل الدخول لتنفيذ الحذف.'
      using errcode = '42501';
  end if;

  if not public.awexen_can_delete_records() then
    raise exception 'حذف السجلات متاح للمالك أو المدير فقط.'
      using errcode = '42501';
  end if;

  if p_table is null or p_table not in (
    'contact_messages', 'quote_requests', 'initiative_applications',
    'newsletter_subscribers', 'job_applications', 'ai_inquiries'
  ) then
    raise exception 'هذا الجدول غير مدعوم في نظام الحذف.'
      using errcode = '22023';
  end if;

  v_text_ids := array(
    select btrim(x)
    from unnest(coalesce(p_ids, '{}'::text[])) as x
    where btrim(x) <> ''
  );

  if coalesce(array_length(v_text_ids, 1), 0) = 0 then
    raise exception 'لم يتم تحديد أي سجل للحذف.'
      using errcode = '22023';
  end if;

  if array_length(v_text_ids, 1) > 200 then
    raise exception 'الحد الأقصى لحذف دفعة واحدة هو 200 سجل.'
      using errcode = '22023';
  end if;

  if p_table = 'contact_messages' then
    begin
      v_bigint_ids := array(select x::bigint from unnest(v_text_ids) as x);
    exception when invalid_text_representation then
      raise exception 'معرّف سجل غير صالح.'
        using errcode = '22023';
    end;

    with deleted as (
      delete from public.contact_messages
      where id = any(v_bigint_ids)
      returning id, name, email
    )
    select
      coalesce(jsonb_agg(jsonb_build_object('id', id::text, 'label', coalesce(name, email))), '[]'::jsonb),
      coalesce(array_agg(id::text), '{}'::text[])
    into v_labels, v_deleted_ids
    from deleted;

  elsif p_table = 'quote_requests' then
    begin
      v_bigint_ids := array(select x::bigint from unnest(v_text_ids) as x);
    exception when invalid_text_representation then
      raise exception 'معرّف سجل غير صالح.'
        using errcode = '22023';
    end;

    select coalesce(
      jsonb_agg(jsonb_build_object('id', id::text, 'label', coalesce(name, email))),
      '[]'::jsonb
    )
    into v_labels
    from public.quote_requests
    where id = any(v_bigint_ids);

    with archived as (
      update public.quote_requests
      set deleted_at = now(),
          deleted_by = v_actor,
          deletion_reason = v_reason
      where id = any(v_bigint_ids)
        and deleted_at is null
        and (quoted_amount is not null or status in ('quoted', 'accepted'))
      returning id
    )
    select coalesce(array_agg(id::text), '{}'::text[])
    into v_archived_ids
    from archived;

    with deleted as (
      delete from public.quote_requests
      where id = any(v_bigint_ids)
        and quoted_amount is null
        and coalesce(status, 'new') not in ('quoted', 'accepted')
      returning id
    )
    select coalesce(array_agg(id::text), '{}'::text[])
    into v_deleted_ids
    from deleted;

  elsif p_table = 'initiative_applications' then
    begin
      v_bigint_ids := array(select x::bigint from unnest(v_text_ids) as x);
    exception when invalid_text_representation then
      raise exception 'معرّف سجل غير صالح.'
        using errcode = '22023';
    end;

    with deleted as (
      delete from public.initiative_applications
      where id = any(v_bigint_ids)
      returning id, applicant_name, business_name
    )
    select
      coalesce(jsonb_agg(jsonb_build_object('id', id::text, 'label', coalesce(applicant_name, business_name))), '[]'::jsonb),
      coalesce(array_agg(id::text), '{}'::text[])
    into v_labels, v_deleted_ids
    from deleted;

  elsif p_table = 'newsletter_subscribers' then
    begin
      v_bigint_ids := array(select x::bigint from unnest(v_text_ids) as x);
    exception when invalid_text_representation then
      raise exception 'معرّف سجل غير صالح.'
        using errcode = '22023';
    end;

    with deleted as (
      delete from public.newsletter_subscribers
      where id = any(v_bigint_ids)
      returning id, email
    )
    select
      coalesce(jsonb_agg(jsonb_build_object('id', id::text, 'label', email)), '[]'::jsonb),
      coalesce(array_agg(id::text), '{}'::text[])
    into v_labels, v_deleted_ids
    from deleted;

  elsif p_table = 'job_applications' then
    begin
      v_uuid_ids := array(select x::uuid from unnest(v_text_ids) as x);
    exception when invalid_text_representation then
      raise exception 'معرّف سجل غير صالح.'
        using errcode = '22023';
    end;

    select coalesce(
      jsonb_agg(jsonb_build_object(
        'id', id::text,
        'label', coalesce(full_name, email),
        'reason', 'المتقدم مقبول بالفعل؛ السجل محفوظ لأغراض التوظيف.'
      )),
      '[]'::jsonb
    )
    into v_blocked
    from public.job_applications
    where id = any(v_uuid_ids)
      and status = 'accepted';

    with deleted as (
      delete from public.job_applications
      where id = any(v_uuid_ids)
        and status <> 'accepted'
      returning id, full_name, email, cv_url
    )
    select
      coalesce(jsonb_agg(jsonb_build_object('id', id::text, 'label', coalesce(full_name, email))), '[]'::jsonb),
      coalesce(array_agg(id::text), '{}'::text[]),
      coalesce(
        jsonb_agg(distinct cv_url) filter (where cv_url is not null and cv_url <> ''),
        '[]'::jsonb
      )
    into v_labels, v_deleted_ids, v_storage
    from deleted;

  elsif p_table = 'ai_inquiries' then
    begin
      v_uuid_ids := array(select x::uuid from unnest(v_text_ids) as x);
    exception when invalid_text_representation then
      raise exception 'معرّف سجل غير صالح.'
        using errcode = '22023';
    end;

    with deleted as (
      delete from public.ai_inquiries
      where id = any(v_uuid_ids)
      returning id, question
    )
    select
      coalesce(jsonb_agg(jsonb_build_object('id', id::text, 'label', left(question, 120))), '[]'::jsonb),
      coalesce(array_agg(id::text), '{}'::text[])
    into v_labels, v_deleted_ids
    from deleted;
  end if;

  if coalesce(array_length(v_deleted_ids, 1), 0) > 0 then
    insert into public.admin_deletion_log (
      actor_id, actor_email, actor_role, target_table, action,
      record_ids, record_labels, record_count, reason
    ) values (
      v_actor, v_email, v_role, p_table, 'hard_delete',
      to_jsonb(v_deleted_ids), v_labels, array_length(v_deleted_ids, 1), v_reason
    );
  end if;

  if coalesce(array_length(v_archived_ids, 1), 0) > 0 then
    insert into public.admin_deletion_log (
      actor_id, actor_email, actor_role, target_table, action,
      record_ids, record_labels, record_count, reason
    ) values (
      v_actor, v_email, v_role, p_table, 'soft_delete',
      to_jsonb(v_archived_ids), v_labels, array_length(v_archived_ids, 1), v_reason
    );
  end if;

  return jsonb_build_object(
    'table', p_table,
    'deleted', coalesce(array_length(v_deleted_ids, 1), 0),
    'archived', coalesce(array_length(v_archived_ids, 1), 0),
    'deleted_ids', to_jsonb(v_deleted_ids),
    'archived_ids', to_jsonb(v_archived_ids),
    'blocked', v_blocked,
    'storage_urls', v_storage
  );
end;
$$;

revoke all on function public.awexen_admin_delete_records(text, text[], text)
  from public, anon;
grant execute on function public.awexen_admin_delete_records(text, text[], text)
  to authenticated;

